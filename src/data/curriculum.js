export const generateStudyPlan = (examType, selectedTopics) => {
    // Simple mock generator to satisfy the import
    const days = ["Pazartesi", "Salı", "Çarşamba", "Perşembe", "Cuma", "Cumartesi", "Pazar"];
    const plan = {};

    // Distribute topics randomly
    days.forEach(day => {
        plan[day] = [];
        // Add 3-4 slots per day
        for (let i = 0; i < 4; i++) {
            if (selectedTopics && selectedTopics.length > 0) {
                const randomTopic = selectedTopics[Math.floor(Math.random() * selectedTopics.length)];
                plan[day].push({
                    time: `${10 + i * 2}:00`,
                    lesson: randomTopic.lesson,
                    topic: randomTopic.topic,
                    type: Math.random() > 0.7 ? 'Soru Çözümü' : 'Konu Çalışması'
                });
            } else {
                // Fallback if no topics selected
                plan[day].push({
                    time: `${10 + i * 2}:00`,
                    lesson: "Genel Tekrar",
                    topic: "Ders Çalışma Saati",
                    type: "Tekrar"
                });
            }
        }
    });
    return plan;
};
